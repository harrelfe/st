##  ---------------------------------------------------------------------
##  Weight truncated by death: what a survivor-only analysis reports, and
##  what a discrete-time first-order Markov model reports, on the same data.
##
##  The simulation is rigged so that the truth is known exactly:
##    * treatment changes NO individual's weight, at any week
##    * treatment saves light (frail) patients and kills heavy (robust)
##      ones in exactly offsetting numbers, so marginal survival is
##      identical in the two arms
##
##  Hence the arm-level survival comparison -- the check offered in support
##  of assuming S(1) = S(0) -- has nothing to detect, while a survivor-only
##  contrast of week-m weight reports an effect that does not exist.
##  ---------------------------------------------------------------------

require(rms)
require(data.table)
require(tinyplot)
tinytheme('dynamic')
ia <- interactive()
options(prType = if(ia) 'html' else 'plain')
if(! ia) pdf("plots.pdf", width = 7, height = 7)

m      <- 26        # weeks of scheduled follow-up
npg    <- 6000      # patients per treatment arm
sdlev  <- 5         # between-patient SD of true weight level (kg)
sdmeas <- 3         # SD of a single weight determination (kg)
wtdead <- 1000      # weight value signifying death; exceeds every real
                    # weight, so it is automatically the worst ordinal state
pfrail <- 0.5       # P(frail)

##  Probability of surviving to week m, by frailty and arm.  Defined once
##  here so that the generator and the coupling calculations below cannot
##  drift apart.
psurv <- matrix(c(0.80, 0.90,          # frail  (light): treatment saves
                  0.95, 0.85),         # robust (heavy): treatment kills
                nrow = 2, byrow = TRUE,
                dimnames = list(c('frail', 'robust'), c('control', 'active')))

##  ---------------------------------------------------------------------
##  Data generating function for ONE patient
##  ---------------------------------------------------------------------
##  Arguments
##    tx : 0 = control, 1 = active treatment
##    m  : number of weeks of scheduled follow-up
##
##  The patient has an unobservable frailty U.  U does two things: it sets
##  the patient's true weight level, and it sets the patient's risk of
##  dying.  That is the only link between weight and death.
##
##    U = 1  frail   true weight level centered at 60 kg
##    U = 0  robust  true weight level centered at 80 kg
##
##  Treatment appears NOWHERE in the weight process below.  It enters only
##  the survival probability.  So the true causal effect of treatment on
##  weight is exactly zero, for every patient, at every week.  Treatment is
##  also independent of U, so the week-0 weight distribution is the same in
##  the two arms by construction.
##
##  Probability of surviving to week m (the psurv matrix above):
##
##                        control   active
##      frail  (light)      0.80     0.90    treatment saves the frail
##      robust (heavy)      0.95     0.85    treatment kills the robust
##
##  With U equally likely, marginal survival is 0.5(.80) + 0.5(.95) = .875
##  under control and 0.5(.90) + 0.5(.85) = .875 under treatment.  The two
##  are identical by construction, at every sample size.
##
##  Survival is generated by a constant weekly hazard, so it is stochastic
##  given everything about the patient.  That is not in conflict with the
##  potential-outcomes framework, which treats S(0) and S(1) as fixed
##  attributes: a hazard model is the same model with the latent uniform V
##  left outside the patient instead of inside.  Drawing V once and
##  applying BOTH arms' hazards to it puts V inside the patient and
##  materialises the pair (S0, S1), so the extent to which S(1) = S(0)
##  fails can be counted rather than argued about.  Only the arm the
##  patient was actually randomised to generates observed records.
##
##  Records returned, one row per scheduled visit:
##    weeks 0, 1, ..., tlast   real weights, where tlast is the last
##                             scheduled week strictly before death
##    one further row          only if death occurs within follow-up; it
##                             carries week tlast + 1 and wt = wtdead
##
##  U, S0 and S1 are also returned.  They are the unobservable truth, used
##  only to report what the design did; no model below ever sees them.
##
##  Nothing is ever missing.  A patient alive at week m contributes exactly
##  m + 1 rows; a patient who dies contributes a number of rows that varies
##  with the week of death.
##  ---------------------------------------------------------------------

gen1 <- function(tx, m) {
  U      <- rbinom(1, 1, pfrail)                    # 1 = frail, 0 = robust
  level  <- 80 - 20 * U + rnorm(1, 0, sdlev)        # true weight level, kg
  p      <- psurv[2L - U, ]                         # c(control, active)
  ##  One uniform per patient, shared by the two arms' hazards.  V < p[a]
  ##  is exactly survival to week m under arm a, so the potential survival
  ##  indicators follow immediately.
  V      <- runif(1)
  tdeath <- -log(V) / (-log(p[tx + 1L]) / m)        # realised death time
  S0     <- V < p['control']                        # would survive under 0
  S1     <- V < p['active' ]                        # would survive under 1
  ##  last scheduled week strictly before death, capped at m.  as.integer()
  ##  matters: data.table requires the same column types for every group,
  ##  and ceiling() returns double.
  tlast  <- as.integer(min(m, ceiling(tdeath) - 1))
  week   <- 0L : tlast
  wt     <- level + rnorm(length(week), 0, sdmeas)
  if(tdeath <= m) {                                 # death within follow-up
    week <- c(week, tlast + 1L)
    wt   <- c(wt,   wtdead)
  }
  data.table(week = week, wt = wt, U = U, S0 = S0, S1 = S1)
}

##  ---------------------------------------------------------------------
##  Run the generator once per patient.  The grid holds one row per
##  patient: a patient number within arm, the follow-up duration, and the
##  randomised treatment.  Crossing patient number with treatment gives
##  npg patients in each arm.
##  ---------------------------------------------------------------------
set.seed(23)
grid <- setDT(expand.grid(i = 1 : npg, m = m, tx = 0 : 1))
grid[, id := .I]
dall <- grid[, gen1(tx, m), by = .(id, tx)]

##  Death indicator and the patient's baseline weight on every record
dall[, dead := wt == wtdead]
dall[, wt0  := wt[week == 0], by = id]

##  ---------------------------------------------------------------------
##  What the design did to individual survival, and what the observed data
##  could never tell us about it
##  ---------------------------------------------------------------------
##  Sharing one uniform between the arms gives the comonotonic coupling,
##  which MINIMISES the number of patients whose survival treatment
##  changes.  The observed data can never identify the coupling, because
##  S(0) and S(1) are never both seen.  But they do not need to: within
##  each frailty stratum the two survival probabilities differ by 0.10, and
##  the Frechet lower bound on discordance is that absolute difference, so
##  NO coupling whatever can make S(1) = S(0) hold for more than 90% of
##  patients.  The violation is a property of the design, not of a joint
##  distribution we chose.
##  ---------------------------------------------------------------------

tru  <- dall[week == 0, .(U, S0, S1)]
p0   <- psurv[, 'control']
p1   <- psurv[, 'active' ]
wts  <- c(frail = pfrail, robust = 1 - pfrail)
cpl  <- rbind(`comonotonic (used here)` = abs(p1 - p0),
              `independent`             = p1 * (1 - p0) + p0 * (1 - p1),
              `Frechet minimum`         = abs(p1 - p0),
              `Frechet maximum`         = p1 + p0 - 2 * pmax(0, p1 + p0 - 1))
cpl  <- cbind(cpl, overall = as.vector(cpl %*% wts))

cat(sprintf('\nRealised effect of treatment on individual survival to week %d\n', m),
    sprintf('  S(1) != S(0) for %.2f%% of patients\n',
            100 * tru[, mean(S0 != S1)]),
    sprintf('    saved  (would have died under control) : %.2f%%\n',
            100 * tru[, mean(!S0 &  S1)]),
    sprintf('    killed (would have lived under control): %.2f%%\n',
            100 * tru[, mean( S0 & !S1)]),
    sprintf('  by stratum: %.2f%% of the frail, %.2f%% of the robust\n',
            100 * tru[U == 1, mean(S0 != S1)], 100 * tru[U == 0, mean(S0 != S1)]),
    sprintf('\nP(S(1) != S(0)) under couplings consistent with this design\n'),
    sep = '')
print(round(100 * cpl, 2))
cat(sprintf('  (percent; the coupling is unidentifiable, the floor of %.0f%% is not)\n',
            100 * cpl['Frechet minimum', 'overall']))

##  ---------------------------------------------------------------------
##  Figure 1: the survivor-only artifact is manufactured by mortality
##
##  For each week, among patients still alive that week, compute
##    (a) the cross-sectional treatment contrast in weight, and
##    (b) the treatment contrast in change from baseline weight.
##  Plot both against the percentage of patients who have died by then.
##
##  A composition artifact is pinned to zero before anyone has died and
##  must grow as deaths accumulate.  A real effect on weight is under no
##  such constraint.  Differencing from baseline removes the patient's
##  weight level, which is the quantity selection operates on, so (b)
##  stays at zero throughout while (a) tracks cumulative mortality.
##  ---------------------------------------------------------------------

npat <- uniqueN(dall$id)

##  A patient alive at week t has exactly one record at week t, and a
##  patient who died earlier has none, so counting records gives both the
##  risk set and cumulative mortality.
tc <- dall[dead == FALSE & week >= 1, {
  y1 <- wt[tx == 1]
  y0 <- wt[tx == 0]
  c1 <- (wt - wt0)[tx == 1]
  c0 <- (wt - wt0)[tx == 0]
  .(nalive    = .N,
    level     = mean(y1) - mean(y0),
    level_se  = sqrt(var(y1) / length(y1) + var(y0) / length(y0)),
    change    = mean(c1) - mean(c0),
    change_se = sqrt(var(c1) / length(c1) + var(c0) / length(c0)))
}, by = week][order(week)]

tc[, pct_dead := 100 * (1 - nalive / npat)]

L <- melt(tc,
          id.vars       = .q(week, pct_dead),
          measure.vars  = list(.q(level, change), .q(level_se, change_se)),
          value.name    = .q(est, se),
          variable.name = 'analysis')
L[, analysis := factor(analysis, 1 : 2,
                       c('Weight among survivors',
                         'Change from baseline among survivors'))]
L[, `:=`(lo = est - 1.96 * se, hi = est + 1.96 * se)]

# Treatment contrasts among patients still alive, plotted against the percentage who have died by that week, with 0.95 confidence bands. Treatment changes no patient's weight, yet the contrast in weight level tracks cumulative mortality almost exactly (r = -0.99), reaching -1.19 kg once 12.8% have died. The contrast in change from baseline, which cancels the weight level that mortality selects on, stays near zero throughout.

plt(est ~ pct_dead | analysis, data = L, ymin = lo, ymax = hi,
    type = type_ribbon(),
    xlab = 'Patients who have died by this week (%)',
    ylab = 'Treatment contrast (kg)')
abline(h = 0, lty = 1)

##  Swap pct_dead for week on the x axis to show the same thing against
##  time: plt(est ~ week | analysis, ...)

##  The transitions actually modelled.  Attaching the previous week's
##  weight by an inner self-join gives the first-order Markov covariate and
##  at the same time drops week 0, which has no predecessor.  Because no
##  record is ever generated after death, yprev is always a real weight,
##  and no value anywhere in the data is missing.
Y0 <- dall[week == 0, wt]
d  <- dall[dall[, .(id, week = week + 1L, yprev = wt)],
           on = .(id, week), nomatch = 0]
dl <- d[dead == FALSE]

plt(~ Y0, type = type_histogram(breaks = 100))

##  ---------------------------------------------------------------------
##  Description, including the baseline balance that randomisation buys
##  ---------------------------------------------------------------------
b0   <- dall[week == 0, .(n = .N, mean = mean(wt), sd = sd(wt)), by = tx][order(tx)]
b0p  <- t.test(wt ~ tx, data = dall[week == 0])$p.value
b0ks <- suppressWarnings(ks.test(dall[week == 0 & tx == 0, wt],
                                 dall[week == 0 & tx == 1, wt])$p.value)
surv <- dall[, .(alive = !any(dead)), by = .(id, tx)]
sm   <- surv[, .(n = .N, alive = sum(alive)), by = tx][order(tx)]
stest<- prop.test(rev(sm$alive), rev(sm$n))$p.value
npr  <- dall[, .(k = .N), by = id][surv, on = 'id']

cat(sprintf('\nPatients: %d control, %d active\n', sm$n[1], sm$n[2]),
    sprintf('Records generated: %d   transitions modelled: %d   deaths: %d\n',
            nrow(dall), nrow(d), sum(d$dead)),
    sprintf('Distinct weight values among transitions: %d\n', uniqueN(d$wt)),
    sprintf('Records per patient: always %d for a survivor, %d to %d for one who dies\n',
            m + 1L, npr[alive == FALSE, min(k)], npr[alive == FALSE, max(k)]),
    sprintf('\nWeek-0 weight: %.3f kg (SD %.3f) control, %.3f kg (SD %.3f) active\n',
            b0$mean[1], b0$sd[1], b0$mean[2], b0$sd[2]),
    sprintf('  t-test p = %.3f, Kolmogorov-Smirnov p = %.3f  <- identical by construction\n',
            b0p, b0ks),
    sprintf('\nWeek-%d survival: %.4f control, %.4f active\n',
            m, sm$alive[1] / sm$n[1], sm$alive[2] / sm$n[2]),
    sprintf('  test of equal survival p = %.3f   <- the check that is offered\n',
            stest),
    sep = '')

##  ---------------------------------------------------------------------
##  What a cross-sectional survivor analysis reports
##  ---------------------------------------------------------------------
wm <- dall[week == m & !dead]
cat(sprintf('\nWeek-%d survivors only, weight in kg\n', m),
    sprintf('  survivor contrast (active - control)  : %+.3f kg  <- truth is 0\n',
            wm[tx == 1, mean(wt)] - wm[tx == 0, mean(wt)]),
    sprintf('  given previous weight                 : %+.3f kg\n',
            coef(ols(wt ~ rcs(yprev, 4) + tx, data = dl))['tx']),
    sprintf('  given previous and baseline weight    : %+.3f kg\n',
            coef(ols(wt ~ rcs(yprev, 4) + rcs(wt0, 4) + tx, data = dl))['tx']),
    sep = '')

##  ---------------------------------------------------------------------
##  Markov-1 proportional odds model on the combined state.  Because death
##  is coded as a weight of wtdead, the combined ordinal state is just wt.
##  Baseline weight enters as its own term, not only as the previous state
##  at week 1, so it is allowed a permanent effect.  It is a second noisy
##  measurement of the same latent weight level, so including it sharpens
##  the proxy for the unobservable frailty that drives mortality.
##  ---------------------------------------------------------------------
dd <- datadist(d); options(datadist = 'dd')
f  <- orm(wt ~ rcs(yprev, 4) + rcs(wt0, 4) + week + tx, data = d)
f
# Olinks was run on round(wt, 3) and showed that the logit
# link had the best fit in terms of deviance.
# probit and cloglog would not work with >200,000 intercepts
# Olinks(f)
cat('\nMarkov-1 PO on the combined state (death = worst)\n')
print(anova(f))

##  ---------------------------------------------------------------------
##  The same transitions fitted separately.  Treatment acts on the death
##  transition and not on weight, so one PO summary blends two different
##  things; fitting them apart is the multistate view.
##  ---------------------------------------------------------------------
fw <- orm(wt   ~ rcs(yprev, 4) + rcs(wt0, 4) + week + tx, data = dl)
fd <- lrm(dead ~ rcs(yprev, 4) * tx + rcs(wt0, 4) + week, data = d)

cat(sprintf('\nWeight transition among the living\n'),
    sprintf('  tx log odds ratio %+.4f (SE %.4f)   <- should be 0\n',
            coef(fw)['tx'], sqrt(vcov(fw)['tx', 'tx'])),
    sep = '')
print(anova(fw))

##  ---------------------------------------------------------------------
##  Figure 2 and the death-transition gradient
##  ---------------------------------------------------------------------
ws <- seq(50, 95, length = 200)
k  <- contrast(fd,
               list(tx = 1, yprev = ws, wt0 = ws, week = round(m / 2)),
               list(tx = 0, yprev = ws, wt0 = ws, week = round(m / 2)),
               expand = FALSE)
k <- k[.q(yprev, Contrast, Lower, Upper)]

##  True weekly hazard ratios implied by psurv, for the reference lines
hrtrue <- log(psurv[, 'active']) / log(psurv[, 'control'])

# Treatment odds ratio for death in the following week as a function of weight in the previous week, from the first-order Markov logistic transition model, with 0.95 confidence band. The solid line marks no effect; the dashed lines are the true weekly hazard ratios built into the simulation, 0.472 for frail patients and 3.168 for robust ones. The model recovers both without ever observing frailty, crossing 1.0 just below 70 kg -- the midpoint of the two latent weight centres, where weight no longer discriminates between them.

plt(exp(Contrast) ~ yprev, data = k, ymin = exp(Lower), ymax = exp(Upper),
    type = type_ribbon(), log = 'y',
    xlab = 'Weight in the previous week (kg)',
    ylab = 'Treatment odds ratio for death in the following week')
abline(h = c(hrtrue['frail'], 1, hrtrue['robust']), lty = c(2, 1, 2))

##  Display the gradient for patients whose weight has been stable, so
##  baseline and previous weight agree; otherwise the two frailty proxies
##  would be held at conflicting values.
ws <- c(55, 62, 70, 78, 85)
nd <- expand.grid(yprev = ws, tx = 0 : 1, week = round(m / 2))
nd$wt0 <- nd$yprev
nd$lp <- predict(fd, nd)
cat('\nDeath transition: treatment odds ratio by previous weight\n')
print(data.frame(`previous weight (kg)`      = ws,
                 `tx OR for dying this week` =
                   round(exp(nd$lp[nd$tx == 1] - nd$lp[nd$tx == 0]), 2),
                 check.names = FALSE), row.names = FALSE)
cat(sprintf('\nTrue weekly hazard ratios: %.3f frail, %.3f robust\n',
            hrtrue['frail'], hrtrue['robust']))
print(anova(fd))

